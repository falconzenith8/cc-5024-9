// Cubemap manifest (mapping metadata).
//
// The manifest is the contract between the converter, the viewer and any
// downstream consumer. It records the exact face order, per-face image axes,
// pixel-centre convention, handoff edges and the resampling/filter settings
// that produced the pixels. The viewer reads it rather than hard-coding
// assumptions, so an older or custom conversion can still be inspected.

import fs from 'node:fs';
import path from 'node:path';
import { FACES, EDGE_ADJACENCY, EDGE_SIDES } from './geometry.js';

export const MANIFEST_VERSION = 1;
export const MANIFEST_FILE = 'cubemap.json';

export const FACE_FILES = Object.freeze([
  'px.png',
  'nx.png',
  'py.png',
  'ny.png',
  'pz.png',
  'nz.png',
]);

export function buildMapping(faceSize) {
  return {
    convention: 'panorama-cubemap-studio/right-handed-outward-cameras',
    world: {
      axes: '+X right, +Y up, +Z forward (right-handed)',
      longitude: 'theta = atan2(x, z), -pi..pi, column 0 at -pi',
      latitude: 'phi = asin(y / |v|), -pi/2..pi/2, row 0 at +pi/2',
      equirectPixelCentre: 'theta = -pi + 2*pi*(px+0.5)/W ; phi = +pi/2 - pi*(py+0.5)/H',
      seam: 'longitude is periodic; column W-1 neighbours column 0',
    },
    faceSize,
    faceOrder: FACES.map((f) => f.name),
    faces: FACES.map((f) => ({
      id: f.id,
      name: f.name,
      file: FACE_FILES[f.id],
      centreDirection: f.F,
      imageRightWorld: f.R,
      imageDownWorld: f.D,
      handedness: 'det(right, down, centre) = +1',
      orientation:
        'image is what an outward-looking camera at the origin sees; ' +
        'image right = imageRightWorld, image down = imageDownWorld',
      uvToDirection:
        'D = centre + u*imageRight + v*imageDown, (u,v) in [-1,1]; ' +
        'pixel (i,j) centre: u = -1 + 2*(i+0.5)/N, v = -1 + 2*(j+0.5)/N',
      pixelCentre: 'continuous pixel index coordinates; integer i,j is the texel centre',
    })),
    edges: EDGE_ADJACENCY.map((e) => ({
      face: e.face,
      faceName: e.faceName,
      edge: e.edge,
      side: e.side,
      neighbor: e.neighbor,
      neighborName: e.neighborName,
      neighborEdge: e.neighborEdge,
      neighborSide: e.neighborSide,
      traversal: e.reversed ? 'opposite' : 'same',
      note: 'traversal is along each face edge in its image order (top L->R, right T->B, bottom R->L, left B->T); opposite is the correct cube-net orientation',
    })),
    edgeSideBasis: EDGE_SIDES,
    seamPolicy: {
      equirectHorizontal: 'periodic, sampled with wrap-around; no black border',
      equirectPoles: 'clamped to the last row (half-texel polar caps)',
      cubeEdges: 'shared by geometry; no separate border pixels',
    },
    filtering: {
      dtype: 'uint8 encoded values',
      linearLight: false,
      equirectToCube:
        'area integration of the exact projected footprint per face texel; ' +
        'longitude intervals are periodic, latitude bands use exact spherical ' +
        'solid angle; degenerate near-unit footprints use bilinear reconstruction',
      cubeToEquirect:
        'stratified direction supersampling sized from the direction Jacobian; ' +
        'samples within one texel of a face edge blend both faces to avoid seams',
      kernel: 'box (per-texel footprint)',
    },
    notes: [
      'All faces are generated by projection; no face is hand-drawn.',
      'No face is vertically flipped: image down is a world-space down component for every face.',
      'Cube->equirect is a resampling operation and is not byte-lossless.',
    ],
  };
}

export function writeManifest(dir, { direction, faceSize, filter, source, files, metrics, elapsedMs }) {
  const manifest = {
    version: MANIFEST_VERSION,
    format: 'cubemap-faces',
    direction,
    createdAt: new Date().toISOString(),
    engine: 'panorama-cubemap-studio',
    filter,
    faceSize,
    source,
    files,
    mapping: buildMapping(faceSize),
    metrics: metrics ?? null,
    elapsedMs: elapsedMs ?? null,
  };
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, MANIFEST_FILE), JSON.stringify(manifest, null, 2) + '\n');
  return manifest;
}

export function readManifest(dir) {
  const file = path.join(dir, MANIFEST_FILE);
  if (!fs.existsSync(file)) {
    throw new Error(`missing ${MANIFEST_FILE} in ${dir}; run the converter first`);
  }
  const manifest = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (manifest.version !== MANIFEST_VERSION) {
    throw new Error(`unsupported manifest version ${manifest.version}`);
  }
  if (!Array.isArray(manifest.files) || manifest.files.length !== 6) {
    throw new Error('manifest must list six face files');
  }
  if (!(manifest.faceSize > 0)) throw new Error('manifest faceSize is missing');
  return manifest;
}
