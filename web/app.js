// Browser viewer for the generated cubemap and its source.
//
// Every view samples the PNG files written by the converter. The sphere view
// is the source equirectangular image; the cube net draws the six faces in
// their stored pixel orientation; the direction map colour-codes the owning
// face. Pointer clicks locate the same direction everywhere and report both
// the source pixel and the owning face pixel.
//
// Geometry is mirrored from src/geometry.js (world +X right, +Y up, +Z
// forward). scripts/verify-web.mjs checks that this copy agrees with the Node
// module on random directions, so the two cannot silently diverge.

const SOURCE_URL = '../output/sample/chart-equirect.png';
const MANIFEST_URL = '../output/sample/faces/cubemap.json';
const ROUNDTRIP_URL = '../output/sample/roundtrip.json';
const CUBE_DIR = '../output/sample/faces/';

const FACES = [
  { F: [1, 0, 0], R: [0, 0, 1], D: [0, -1, 0] },
  { F: [-1, 0, 0], R: [0, 0, -1], D: [0, -1, 0] },
  { F: [0, 1, 0], R: [1, 0, 0], D: [0, 0, -1] },
  { F: [0, -1, 0], R: [1, 0, 0], D: [0, 0, 1] },
  { F: [0, 0, 1], R: [-1, 0, 0], D: [0, -1, 0] },
  { F: [0, 0, -1], R: [1, 0, 0], D: [0, -1, 0] },
];
const FACE_HEX = ['#e63c3c', '#3caade', '#50be5a', '#e1a032', '#5a5adc', '#c846c8'];
const FACE_NAMES = ['+X', '-X', '+Y', '-Y', '+Z', '-Z'];

// Cube net layout is generated by src/net.js from the physical edge table and
// written to web/net.json, so the page cannot invent a different net.
const NET_URL = 'net.json';

const HINTS = {
  sphere: 'Equirectangular source. Column 0 is −180° and wraps to +180°; drag to scrub longitude/latitude.',
  cube: 'Stored face PNGs in a cube net. Click a face to locate that direction. Labels are upright in the stored image.',
  map: 'Face ownership of every direction, same projection as the source. Click to locate.',
};

const els = {};
const state = {
  view: 'sphere',
  source: null,
  manifest: null,
  roundtrip: null,
  net: null,
  faces: [],
  showGrid: true,
  showFaces: true,
  seamBand: false,
  selected: { theta: 0, phi: 0 },
  dragging: false,
  sourceRect: null,
  cubeRects: [],
  pointer: null,
};

const $ = (id) => document.getElementById(id);

const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));
const mod = (a, n) => ((a % n) + n) % n;

function dirFromAngles(theta, phi) {
  const cp = Math.cos(phi);
  return [cp * Math.sin(theta), Math.sin(phi), cp * Math.cos(theta)];
}

function anglesFromDir(x, y, z) {
  return {
    theta: Math.atan2(x, z),
    phi: Math.asin(clamp(y / Math.hypot(x, y, z), -1, 1)),
  };
}

function faceUVFromDir(x, y, z) {
  const ax = Math.abs(x);
  const ay = Math.abs(y);
  const az = Math.abs(z);
  if (ax >= ay && ax >= az) {
    return x >= 0
      ? { face: 0, u: z / ax, v: -y / ax }
      : { face: 1, u: -z / ax, v: -y / ax };
  }
  if (ay >= az) {
    return y >= 0
      ? { face: 2, u: x / ay, v: -z / ay }
      : { face: 3, u: x / ay, v: z / ay };
  }
  return z >= 0
    ? { face: 4, u: -x / az, v: -y / az }
    : { face: 5, u: x / az, v: -y / az };
}

function faceDir(face, u, v) {
  const f = FACES[face];
  return [
    f.F[0] + u * f.R[0] + v * f.D[0],
    f.F[1] + u * f.R[1] + v * f.D[1],
    f.F[2] + u * f.R[2] + v * f.D[2],
  ];
}

/** Continuous source image coordinates (pixel centres at half-integers). */
function sourcePixelFromDir(x, y, z, W, H) {
  const { theta, phi } = anglesFromDir(x, y, z);
  return {
    x: ((theta + Math.PI) / (2 * Math.PI)) * W - 0.5,
    y: ((Math.PI / 2 - phi) / Math.PI) * H - 0.5,
    theta,
    phi,
  };
}

function dirFromSourcePixel(px, py, W, H) {
  const theta = -Math.PI + (2 * Math.PI * (px + 0.5)) / W;
  const phi = Math.PI / 2 - (Math.PI * (py + 0.5)) / H;
  return dirFromAngles(theta, phi);
}

// ---------------------------------------------------------------------------
// Loading

async function loadImage(url) {
  const img = new Image();
  img.decoding = 'async';
  img.src = url;
  await img.decode();
  return img;
}

function imageToCanvas(img) {
  const c = document.createElement('canvas');
  c.width = img.naturalWidth;
  c.height = img.naturalHeight;
  c.getContext('2d', { willReadFrequently: true }).drawImage(img, 0, 0);
  return c;
}

function readPixel(canvas, x, y) {
  const ctx = canvas.getContext('2d', { willReadFrequently: true });
  const d = ctx.getImageData(clamp(x, 0, canvas.width - 1), clamp(y, 0, canvas.height - 1), 1, 1).data;
  return [d[0], d[1], d[2]];
}

export async function init() {
  els.mainCanvas = $('main-canvas');
  els.inspectorCanvas = $('inspector-canvas');
  els.mainTitle = $('main-title');
  els.mainMeta = $('main-meta');
  els.viewHint = $('view-hint');

  const [sourceImg, manifest, roundtrip, net] = await Promise.all([
    loadImage(SOURCE_URL),
    fetch(MANIFEST_URL).then((r) => r.json()),
    fetch(ROUNDTRIP_URL).then((r) => r.json()).catch(() => null),
    fetch(NET_URL).then((r) => r.json()),
  ]);
  state.source = {
    width: sourceImg.naturalWidth,
    height: sourceImg.naturalHeight,
    canvas: imageToCanvas(sourceImg),
  };
  state.manifest = manifest;
  state.roundtrip = roundtrip;
  state.net = net;
  const faceImgs = await Promise.all(manifest.files.map((f) => loadImage(CUBE_DIR + f.file)));
  state.faces = manifest.files.map((f, i) => ({
    face: i,
    name: f.name,
    canvas: imageToCanvas(faceImgs[i]),
  }));

  if (roundtrip?.metrics) {
    const m = roundtrip.metrics;
    $('fact-roundtrip').textContent = `PSNR ${m.psnrDb.toFixed(2)} dB · MAE ${m.mae.toFixed(2)}/255`;
  }

  bindEvents();
  selectView('sphere');
  resize();
  window.__viewerReady = true;
  window.__viewer = {
    state,
    faceUVFromDir,
    netToFace: (face, x, y) => netToFace(net.tiles[face], x, y),
    faceToNet: (face, u, v) => faceToNet(net.tiles[face], u, v),
    faceDir,
    sourcePixelFromDir,
    dirFromSourcePixel,
    anglesFromDir,
    dirFromAngles,
    selectView,
    redraw,
  };
}

function bindEvents() {
  for (const btn of document.querySelectorAll('[data-view]')) {
    btn.addEventListener('click', () => selectView(btn.dataset.view));
  }
  $('toggle-grid').addEventListener('change', (e) => {
    state.showGrid = e.target.checked;
    redraw();
  });
  $('toggle-faces').addEventListener('change', (e) => {
    state.showFaces = e.target.checked;
    redraw();
  });
  $('toggle-seams').addEventListener('change', (e) => {
    state.seamBand = e.target.checked;
    redraw();
  });

  const canvas = els.mainCanvas;
  canvas.addEventListener('pointerdown', (e) => {
    state.dragging = true;
    canvas.setPointerCapture(e.pointerId);
    locateFromEvent(e);
  });
  canvas.addEventListener('pointermove', (e) => {
    state.pointer = { clientX: e.clientX, clientY: e.clientY };
    if (state.dragging) locateFromEvent(e);
    else if (state.view !== 'map') readoutFromEvent(e);
  });
  canvas.addEventListener('pointerup', () => {
    state.dragging = false;
  });
  canvas.addEventListener('pointercancel', () => {
    state.dragging = false;
  });
  window.addEventListener('resize', resize);
}

// ---------------------------------------------------------------------------
// View switching

export function selectView(view) {
  state.view = view;
  for (const btn of document.querySelectorAll('[data-view]')) {
    btn.setAttribute('aria-pressed', String(btn.dataset.view === view));
  }
  els.viewHint.textContent = HINTS[view];
  if (view === 'sphere') {
    els.mainTitle.textContent = `Source equirectangular (${state.source.width}×${state.source.height})`;
    els.mainMeta.textContent = 'column 0 = −180° · wraps to +180°';
  } else if (view === 'cube') {
    els.mainTitle.textContent = 'Cubemap net (stored files)';
    els.mainMeta.textContent = `${state.manifest.mapping.faceSize}² per face`;
  } else {
    els.mainTitle.textContent = 'Direction ownership map';
    els.mainMeta.textContent = 'same projection as the source';
  }
  resize();
}

function resize() {
  if (!els.mainCanvas) return;
  const wrap = els.mainCanvas.parentElement;
  const cssW = Math.max(360, wrap.clientWidth - 20);
  const cssH = state.view === 'cube' ? Math.round(cssW * 0.62) : Math.round(cssW * 0.5);
  els.mainCanvas.style.width = `${cssW}px`;
  els.mainCanvas.style.height = `${cssH}px`;
  const dpr = Math.min(2, window.devicePixelRatio || 1);
  els.mainCanvas.width = Math.round(cssW * dpr);
  els.mainCanvas.height = Math.round(cssH * dpr);
  redraw();
}

// ---------------------------------------------------------------------------
// Rendering

function redraw() {
  if (!state.source) return;
  if (state.view === 'sphere') drawSphere();
  else if (state.view === 'cube') drawCubeNet();
  else drawDirectionMap();
  drawLocator();
}

function drawSphere() {
  const ctx = els.mainCanvas.getContext('2d');
  const cw = els.mainCanvas.width;
  const ch = els.mainCanvas.height;
  const src = state.source;
  const scale = Math.min((cw - 24) / src.width, (ch - 24) / src.height);
  const dw = Math.round(src.width * scale);
  const dh = Math.round(src.height * scale);
  const ox = Math.round((cw - dw) / 2);
  const oy = Math.round((ch - dh) / 2);
  ctx.imageSmoothingEnabled = false;
  ctx.fillStyle = '#05070a';
  ctx.fillRect(0, 0, cw, ch);
  ctx.drawImage(src.canvas, ox, oy, dw, dh);
  state.sourceRect = { ox, oy, dw, dh };
  state.cubeRects = [];

  if (state.showGrid) {
    ctx.save();
    ctx.strokeStyle = 'rgba(255,255,255,0.20)';
    ctx.lineWidth = Math.max(1, cw / 1200);
    for (let lon = -180; lon < 180; lon += 15) {
      const x = ox + ((lon + 180) / 360) * dw;
      ctx.beginPath();
      ctx.moveTo(x, oy);
      ctx.lineTo(x, oy + dh);
      ctx.stroke();
    }
    for (let lat = -75; lat <= 75; lat += 15) {
      const y = oy + ((90 - lat) / 180) * dh;
      ctx.beginPath();
      ctx.moveTo(ox, y);
      ctx.lineTo(ox + dw, y);
      ctx.stroke();
    }
    ctx.restore();
  }

  if (state.seamBand) {
    const bw = Math.max(10, dw * 0.025);
    const stripH = Math.max(24, dh * 0.05);
    const sw = Math.max(8, Math.round(bw));
    ctx.save();
    // Prove periodicity: draw the first and last source columns adjacent.
    ctx.drawImage(src.canvas, 0, 0, Math.min(sw, src.width), src.height, ox, oy, sw, stripH);
    ctx.drawImage(
      src.canvas,
      src.width - Math.min(sw, src.width),
      0,
      Math.min(sw, src.width),
      src.height,
      ox + sw + 2,
      oy,
      sw,
      stripH,
    );
    ctx.strokeStyle = 'rgba(255,150,40,0.95)';
    ctx.lineWidth = Math.max(2, cw / 700);
    ctx.strokeRect(ox + 1, oy + 1, bw, dh - 2);
    ctx.strokeRect(ox + dw - bw - 1, oy + 1, bw, dh - 2);
    ctx.strokeStyle = 'rgba(255,255,255,0.5)';
    ctx.strokeRect(ox - 1, oy - 1, sw * 2 + 6, stripH + 2);
    ctx.restore();
  }

  const sel = state.selected;
  const p = sourcePixelFromDir(...dirFromAngles(sel.theta, sel.phi), src.width, src.height);
  const mx = ox + ((p.theta + Math.PI) / (2 * Math.PI)) * dw;
  const my = oy + (p.y / src.height) * dh;
  const hit = faceUVFromDir(...dirFromAngles(sel.theta, sel.phi));
  ctx.save();
  ctx.strokeStyle = FACE_HEX[hit.face];
  ctx.lineWidth = Math.max(2, cw / 600);
  ctx.beginPath();
  ctx.arc(mx, my, Math.max(8, cw / 120), 0, Math.PI * 2);
  ctx.stroke();
  ctx.beginPath();
  ctx.moveTo(mx - 14, my);
  ctx.lineTo(mx + 14, my);
  ctx.moveTo(mx, my - 14);
  ctx.lineTo(mx, my + 14);
  ctx.stroke();
  ctx.setLineDash([5, 5]);
  ctx.globalAlpha = 0.55;
  ctx.beginPath();
  ctx.moveTo(mx, oy);
  ctx.lineTo(mx, oy + dh);
  ctx.moveTo(ox, my);
  ctx.lineTo(ox + dw, my);
  ctx.stroke();
  ctx.restore();
}

function rotateCW(vec, deg) {
  const steps = ((deg / 90) % 4 + 4) % 4;
  let [x, y] = vec;
  for (let i = 0; i < steps; i++) {
    const nx = -y;
    const ny = x;
    x = nx;
    y = ny;
  }
  return [x, y];
}

/** Page-space point inside a net tile for stored face coordinates (u,v). */
function netToFace(tile, x, y) {
  const s = [x * 2 - 1, y * 2 - 1];
  const uv = rotateCW(s, (360 - tile.rot) % 360);
  return { u: uv[0], v: uv[1] };
}

/** Stored face coordinates (u,v) for a point inside a net tile (x,y in 0..1). */
function faceToNet(tile, u, v) {
  const s = rotateCW([u, v], tile.rot);
  return { x: (s[0] + 1) / 2, y: (s[1] + 1) / 2 };
}

function drawCubeNet() {
  const ctx = els.mainCanvas.getContext('2d');
  const cw = els.mainCanvas.width;
  const ch = els.mainCanvas.height;
  const pad = Math.max(8, cw * 0.01);
  const { cols, rows, tiles } = state.net;
  const cell = Math.floor(Math.min((cw - pad * (cols + 1)) / cols, (ch - pad * (rows + 1)) / rows));
  const gw = cell * cols + pad * (cols + 1);
  const gh = cell * rows + pad * (rows + 1);
  const ox = Math.round((cw - gw) / 2) + pad;
  const oy = Math.round((ch - gh) / 2) + pad;
  ctx.imageSmoothingEnabled = false;
  ctx.fillStyle = '#05070a';
  ctx.fillRect(0, 0, cw, ch);
  state.sourceRect = null;
  state.cubeRects = [];

  for (let f = 0; f < 6; f++) {
    const { col, row, rot } = tiles[f];
    const x = ox + col * (cell + pad);
    const y = oy + row * (cell + pad);
    // Draw the stored face rotated on the page by `rot` so shared edges of the
    // physical cube line up. The rotation is in metadata (web/net.json).
    ctx.save();
    ctx.translate(x + cell / 2, y + cell / 2);
    ctx.rotate((rot * Math.PI) / 180);
    ctx.drawImage(state.faces[f].canvas, -cell / 2, -cell / 2, cell, cell);
    ctx.restore();
    state.cubeRects.push({ face: f, x, y, w: cell, h: cell });
    ctx.save();
    ctx.strokeStyle = FACE_HEX[f];
    ctx.lineWidth = Math.max(1.5, cw / 900);
    ctx.strokeRect(x + 1, y + 1, cell - 2, cell - 2);
    const tagW = Math.max(34, cell * 0.16);
    const tagH = Math.max(16, cell * 0.075);
    ctx.fillStyle = 'rgba(0,0,0,0.62)';
    ctx.fillRect(x + 4, y + 4, tagW, tagH);
    ctx.fillStyle = '#fff';
    ctx.font = `600 ${Math.round(tagH * 0.7)}px ui-monospace, monospace`;
    ctx.fillText(FACE_NAMES[f], x + 8, y + tagH - 1);
    ctx.restore();
  }

  if (state.showFaces) {
    const d = dirFromAngles(state.selected.theta, state.selected.phi);
    const hit = faceUVFromDir(...d);
    const r = state.cubeRects[hit.face];
    const p = faceToNet(tiles[hit.face], hit.u, hit.v);
    const fx = r.x + p.x * r.w;
    const fy = r.y + p.y * r.h;
    ctx.save();
    ctx.strokeStyle = '#fff';
    ctx.lineWidth = Math.max(2, cw / 700);
    ctx.beginPath();
    ctx.arc(fx, fy, Math.max(7, cell * 0.03), 0, Math.PI * 2);
    ctx.stroke();
    ctx.beginPath();
    ctx.moveTo(fx - 11, fy);
    ctx.lineTo(fx + 11, fy);
    ctx.moveTo(fx, fy - 11);
    ctx.lineTo(fx, fy + 11);
    ctx.stroke();
    ctx.restore();
  }
}

function drawDirectionMap() {
  const ctx = els.mainCanvas.getContext('2d');
  const cw = els.mainCanvas.width;
  const ch = els.mainCanvas.height;
  const img = ctx.createImageData(cw, ch);
  for (let j = 0; j < ch; j++) {
    const phi = Math.PI / 2 - (Math.PI * ((j + 0.5) / ch));
    for (let i = 0; i < cw; i++) {
      const theta = -Math.PI + 2 * Math.PI * ((i + 0.5) / cw);
      const d = dirFromAngles(theta, phi);
      const hit = faceUVFromDir(...d);
      const [r, g, b] = hexToRgb(FACE_HEX[hit.face]);
      const edge = Math.max(Math.abs(hit.u), Math.abs(hit.v));
      const shade = 0.5 + 0.5 * (1 - edge * edge);
      const o = (j * cw + i) * 4;
      img.data[o] = r * shade;
      img.data[o + 1] = g * shade;
      img.data[o + 2] = b * shade;
      img.data[o + 3] = 255;
    }
  }
  ctx.putImageData(img, 0, 0);
  state.sourceRect = { ox: 0, oy: 0, dw: cw, dh: ch };
  state.cubeRects = [];

  ctx.save();
  ctx.textAlign = 'center';
  ctx.font = `600 ${Math.max(12, Math.round(cw / 60))}px ui-monospace, monospace`;
  for (let f = 0; f < 6; f++) {
    const F = FACES[f].F;
    const p = sourcePixelFromDir(F[0], F[1], F[2], cw, ch);
    const label = FACE_NAMES[f];
    const tw = ctx.measureText(label).width + 12;
    const th = Math.max(18, cw / 55);
    ctx.fillStyle = 'rgba(0,0,0,0.6)';
    ctx.fillRect(p.x - tw / 2, p.y - th / 2, tw, th);
    ctx.fillStyle = '#fff';
    ctx.fillText(label, p.x, p.y + th * 0.28);
  }
  ctx.restore();

  const d = dirFromAngles(state.selected.theta, state.selected.phi);
  const sel = sourcePixelFromDir(...d, cw, ch);
  ctx.save();
  ctx.strokeStyle = '#fff';
  ctx.lineWidth = Math.max(2, cw / 700);
  ctx.beginPath();
  ctx.arc(sel.x, sel.y, Math.max(8, cw / 150), 0, Math.PI * 2);
  ctx.stroke();
  ctx.restore();
}

function drawLocator() {
  const ctx = els.inspectorCanvas.getContext('2d');
  const sw = els.inspectorCanvas.width;
  const sh = els.inspectorCanvas.height;
  const src = state.source;
  const d = dirFromAngles(state.selected.theta, state.selected.phi);
  const p = sourcePixelFromDir(...d, src.width, src.height);
  const sx = clamp(Math.floor(p.x), 0, src.width - 1);
  const sy = clamp(Math.floor(p.y), 0, src.height - 1);
  const zoom = Math.max(2, Math.floor(sw / 30));
  const cols = Math.floor(sw / zoom);
  const rows = Math.floor(sh / zoom);
  ctx.imageSmoothingEnabled = false;
  ctx.fillStyle = '#05070a';
  ctx.fillRect(0, 0, sw, sh);
  for (let j = 0; j < rows; j++) {
    for (let i = 0; i < cols; i++) {
      const px = mod(sx - Math.floor(cols / 2) + i, src.width);
      const py = clamp(sy - Math.floor(rows / 2) + j, 0, src.height - 1);
      ctx.drawImage(src.canvas, px, py, 1, 1, i * zoom, j * zoom, zoom, zoom);
    }
  }
  const cx = Math.floor(cols / 2) * zoom;
  const cy = Math.floor(rows / 2) * zoom;
  ctx.strokeStyle = '#ffb15c';
  ctx.lineWidth = 2;
  ctx.strokeRect(cx + 1, cy + 1, zoom - 2, zoom - 2);

  const hit = faceUVFromDir(...d);
  const N = state.manifest.mapping.faceSize;
  const fpx = ((hit.u + 1) * N) / 2 - 0.5;
  const fpy = ((hit.v + 1) * N) / 2 - 0.5;
  const tx = clamp(Math.round(fpx), 0, N - 1);
  const ty = clamp(Math.round(fpy), 0, N - 1);
  const [sr, sg, sb] = readPixel(src.canvas, sx, sy);
  const [fr, fg, fb] = readPixel(state.faces[hit.face].canvas, tx, ty);

  $('loc-lon').textContent = `${((p.theta * 180) / Math.PI).toFixed(3)}°`;
  $('loc-lat').textContent = `${((p.phi * 180) / Math.PI).toFixed(3)}°`;
  $('loc-dir').textContent = `(${d.map((v) => v.toFixed(4)).join(', ')})`;
  $('loc-source').textContent = `${sx}, ${sy} of ${src.width}×${src.height}`;
  $('loc-src-color').textContent = `rgb(${sr}, ${sg}, ${sb})`;
  $('loc-face').textContent = `${FACE_NAMES[hit.face]} @ ${tx}, ${ty} of ${N}²`;
  $('loc-uv').textContent = `${hit.u.toFixed(4)}, ${hit.v.toFixed(4)}`;
  $('loc-face-color').textContent = `rgb(${fr}, ${fg}, ${fb})`;
  $('locator-meta').textContent = `source ${sx},${sy} · ${FACE_NAMES[hit.face]} ${tx},${ty}`;
}

// ---------------------------------------------------------------------------
// Pointer mapping

function canvasPoint(evt) {
  const rect = els.mainCanvas.getBoundingClientRect();
  return {
    x: ((evt.clientX - rect.left) / rect.width) * els.mainCanvas.width,
    y: ((evt.clientY - rect.top) / rect.height) * els.mainCanvas.height,
  };
}

function locateFromEvent(evt) {
  const { x, y } = canvasPoint(evt);
  let next = null;
  if (state.view === 'sphere' || state.view === 'map') {
    const r = state.sourceRect;
    if (!r || x < r.ox || x > r.ox + r.dw || y < r.oy || y > r.oy + r.dh) return;
    const theta = ((x - r.ox) / r.dw) * 2 * Math.PI - Math.PI;
    const phi = Math.PI / 2 - ((y - r.oy) / r.dh) * Math.PI;
    next = { theta, phi };
  } else {
    for (const r of state.cubeRects) {
      if (x >= r.x && x < r.x + r.w && y >= r.y && y < r.y + r.h) {
        const uv = netToFace(state.net.tiles[r.face], clamp((x - r.x) / r.w, 0, 1), clamp((y - r.y) / r.h, 0, 1));
        next = anglesFromDir(...faceDir(r.face, uv.u, uv.v));
        break;
      }
    }
  }
  if (!next) return;
  state.selected = next;
  redraw();
  updateReadout(next);
}

function readoutFromEvent(evt) {
  const { x, y } = canvasPoint(evt);
  if (state.view !== 'sphere' || !state.sourceRect) return;
  const r = state.sourceRect;
  if (x < r.ox || x > r.ox + r.dw || y < r.oy || y > r.oy + r.dh) return;
  const theta = ((x - r.ox) / r.dw) * 2 * Math.PI - Math.PI;
  const phi = Math.PI / 2 - ((y - r.oy) / r.dh) * Math.PI;
  updateReadout({ theta, phi });
}

function updateReadout({ theta, phi }) {
  const d = dirFromAngles(theta, phi);
  const hit = faceUVFromDir(...d);
  const N = state.manifest.mapping.faceSize;
  const src = sourcePixelFromDir(...d, state.source.width, state.source.height);
  const sx = clamp(Math.floor(src.x), 0, state.source.width - 1);
  const sy = clamp(Math.floor(src.y), 0, state.source.height - 1);
  $('pixel-readout').textContent =
    `lon ${((theta * 180) / Math.PI).toFixed(2)}° · lat ${((phi * 180) / Math.PI).toFixed(2)}° · ` +
    `source ${sx},${sy} · ${FACE_NAMES[hit.face]} @ ` +
    `${Math.round(((hit.u + 1) * N) / 2 - 0.5)},${Math.round(((hit.v + 1) * N) / 2 - 0.5)}`;
}

function hexToRgb(hex) {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

